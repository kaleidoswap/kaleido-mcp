#!/usr/bin/env node
// Boots dist/index.js over stdio, lists the registered tools and writes docs/TOOLS.md.
import { writeFile, mkdir } from 'node:fs/promises'
import { listTools } from '../tests/mcp-contract-test-utils.mjs'

const root = new URL('..', import.meta.url)
const cwd = root.pathname
const TEST_MNEMONIC = 'abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon about'

const GROUPS = [
  ['KaleidoSwap DEX', n => n.startsWith('kaleidoswap_')],
  ['RLN node (Lightning + RGB)', n => n.startsWith('wdk_')],
  ['Spark wallet', n => n.startsWith('spark_')],
  ['Liquid wallet', n => n.startsWith('liquid_')],
  ['WDK built-in wallet + pricing', n => !n.includes('_')],
  ['Node lifecycle (kaleido CLI)', n => n.startsWith('kaleido_node_')],
  ['MPP / L402 / paid API discovery', n => /^(mpp_|search_paid_apis$|l402_(request_challenge|fetch_resource)$)/.test(n)],
  ['Market data', n => n.startsWith('l402_get_')],
]

const withSeed = await listTools({ cwd, env: { WDK_SEED: TEST_MNEMONIC, SPARK_NETWORK: 'REGTEST' } })
const seedless = new Set((await listTools({ cwd, env: {} })).map(t => t.name))

const aliasOf = new Map()
for (const t of withSeed) {
  const legacy = t.name.match(/^rln_(.+)$/) ?? t.name.match(/^(get_.+)$/)
  if (!legacy) continue
  const canonical = t.name.startsWith('rln_') ? `wdk_${legacy[1]}` : `l402_${legacy[1]}`
  if (withSeed.some(c => c.name === canonical)) aliasOf.set(t.name, canonical)
}

const esc = s => String(s ?? '').split(/\n\s*\n/)[0].replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ').trim()

function params(schema) {
  const props = schema?.properties ?? {}
  const required = new Set(schema?.required ?? [])
  const names = Object.keys(props)
  if (!names.length) return '—'
  return names.map(n => `\`${n}\`${required.has(n) ? '' : '?'}`).join(', ')
}

const row = t => `| \`${t.name}\`${seedless.has(t.name) ? '' : ' **seed**'} | ${params(t.inputSchema)} | ${esc(t.description)} |`

const tools = withSeed.filter(t => !aliasOf.has(t.name))
const seen = new Set()
const out = [
  '# Tools reference',
  '',
  '<!-- Generated by `npm run docs:tools` — do not edit by hand. -->',
  '',
  `${tools.length} tools (plus ${aliasOf.size} legacy aliases). Tools marked **seed** are only registered when \`WDK_SEED\` is set (Liquid tools also accept \`LIQUID_MNEMONIC\`). A \`?\` after a parameter means it is optional.`,
  '',
]

for (const [title, match] of GROUPS) {
  const group = tools.filter(t => !seen.has(t.name) && match(t.name))
  if (!group.length) continue
  out.push(`## ${title}`, '', '| Tool | Parameters | Description |', '| --- | --- | --- |')
  for (const t of group) {
    seen.add(t.name)
    out.push(row(t))
  }
  out.push('')
}

const rest = tools.filter(t => !seen.has(t.name))
if (rest.length) {
  out.push('## Other', '', '| Tool | Parameters | Description |', '| --- | --- | --- |')
  for (const t of rest) out.push(row(t))
  out.push('')
}

out.push('## Legacy aliases', '', 'Kept for older callers; prefer the canonical name.', '', '| Alias | Canonical |', '| --- | --- |')
for (const [alias, canonical] of [...aliasOf].sort()) out.push(`| \`${alias}\` | \`${canonical}\` |`)
out.push('')

await mkdir(new URL('docs/', root), { recursive: true })
await writeFile(new URL('docs/TOOLS.md', root), out.join('\n'))
process.stdout.write(`docs/TOOLS.md: ${tools.length} tools, ${aliasOf.size} aliases\n`)
